"""Turn the WHO Child Growth Standards tables into a compact TypeScript module.

Source (downloaded, not redistributed as spreadsheets):
  weight-for-age   wfa-<sex>-zscore-expanded-tables.xlsx
  length/height-for-age  lhfa-<sex>-zscore-expanded-tables.xlsx
Both are daily tables carrying the LMS parameters. We keep one row per month
from 0 to 36, which is all a 1-3 year old app needs, and derive every
percentile at runtime from L, M and S.
"""

import openpyxl
from pathlib import Path

SRC = Path("/tmp/who")
OUT = Path("/workspace/src/lib/grow/who-data.ts")
MAX_MONTH = 36
DAYS_PER_MONTH = 30.4375


def lms_by_month(path):
    wb = openpyxl.load_workbook(path, read_only=True)
    ws = wb[wb.sheetnames[0]]
    by_day = {}
    for row in ws.iter_rows(min_row=2, values_only=True):
        if not isinstance(row[0], (int, float)):
            continue
        by_day[int(row[0])] = (row[1], row[2], row[3])
    out = []
    for month in range(MAX_MONTH + 1):
        day = round(month * DAYS_PER_MONTH)
        # WHO switches from recumbent length to standing height on day 731.
        # Month 24 lands on day 730 by rounding, which would pick the last
        # length row instead of the first height row.
        if month >= 24:
            day = max(day, 731)
        l, m, s = by_day[day]
        out.append((round(l, 4), round(m, 4), round(s, 5)))
    return out


def fmt(rows):
    return "\n".join(f"  [{l}, {m}, {s}]," for l, m, s in rows)


data = {}
for sex in ("boys", "girls"):
    data[("weight", sex)] = lms_by_month(SRC / f"wfa-{sex}.xlsx")
    data[("height", sex)] = lms_by_month(SRC / f"lhfa-{sex}.xlsx")

# sanity check against the published month tables
checks = [
    (("weight", "boys"), 12, 9.6),
    (("weight", "girls"), 12, 8.9),
    (("height", "boys"), 12, 75.7),
    (("height", "girls"), 12, 74.0),
    (("weight", "boys"), 24, 12.2),
    (("weight", "girls"), 24, 11.5),
    (("height", "boys"), 24, 87.1),
    (("height", "girls"), 24, 85.7),
    (("height", "boys"), 36, 96.1),
    (("height", "girls"), 36, 95.1),
    (("weight", "boys"), 36, 14.3),
    (("weight", "girls"), 36, 13.9),
    (("weight", "boys"), 18, 10.9),
    (("height", "boys"), 18, 82.3),
]
for key, month, expected in checks:
    median = data[key][month][1]
    assert abs(median - expected) < 0.15, f"{key} month {month}: got {median}, expected ~{expected}"
    print(f"ok  {key[0]:6} {key[1]:5} month {month:2}  median {median} (published ~{expected})")

body = f'''/**
 * WHO Child Growth Standards, LMS parameters by month of age (0-36).
 *
 * Each row is [L, M, S] for that month. Any percentile comes from
 *   X = M * (1 + L * S * z) ^ (1 / L)
 * and any measurement's z-score from the inverse. Generated by
 * scripts/build-who.py from the WHO expanded z-score tables; do not edit.
 *
 * Height rows are recumbent length up to 24 months and standing height after,
 * which is how WHO publishes them.
 */

export type Lms = readonly [l: number, m: number, s: number];

export const WHO_WEIGHT_BOYS: readonly Lms[] = [
{fmt(data[("weight", "boys")])}
];

export const WHO_WEIGHT_GIRLS: readonly Lms[] = [
{fmt(data[("weight", "girls")])}
];

export const WHO_HEIGHT_BOYS: readonly Lms[] = [
{fmt(data[("height", "boys")])}
];

export const WHO_HEIGHT_GIRLS: readonly Lms[] = [
{fmt(data[("height", "girls")])}
];

export const WHO_MAX_MONTH = {MAX_MONTH};
'''

OUT.parent.mkdir(parents=True, exist_ok=True)
OUT.write_text(body, encoding="utf-8")
print(f"\nwrote {OUT} ({len(body.splitlines())} lines)")
