import { readdir, writeFile } from "node:fs/promises";
import sharp from "sharp";

/**
 * Works out where each creature's mouth is, so food can be carried to it.
 *
 * Feeding needs a target, and a single centred one is wrong: every revealed
 * creature is posed with its head turned, so its face sits as much as 9.5% of
 * the image width left of centre, and the eye line ranges over eleven points
 * between the shortest and the tallest. At this size that is the difference
 * between a biscuit at the mouth and a biscuit on the cheek.
 *
 * Twenty-four hand-tuned coordinates would rot the moment the art changes, so
 * they are measured instead. The eyes are the only near-black mass in these
 * renders — the darkest thing after them is a nostril — so their centroid is
 * the middle of the face, and the mouth is a fixed drop below it.
 *
 * Emits a generated module rather than doing this at runtime: it is the same
 * answer every time, and decoding 24 images in the browser to find out where
 * to put one biscuit would be absurd.
 */
const SRC = "public/art/pet";
const OUT = "src/lib/grow/mouths.ts";

/** Anything darker than this in all channels is eye. */
const DARK = 70;
/** Eyes are in the top of the frame; this skips dark feet and shadows. */
const LOOK = 0.75;
/**
 * How far below the eye line the mouth sits, as a share of the image height.
 * One constant for every creature, because they are all drawn to the same
 * chunky proportions. Calibrated by eye against the widest and shortest faces.
 */
const DROP = 0.135;

async function faceOf(file) {
  const { data, info } = await sharp(`${SRC}/${file}`).ensureAlpha().raw().toBuffer({ resolveWithObject: true });
  let sx = 0;
  let sy = 0;
  let n = 0;
  for (let y = 0; y < Math.floor(info.height * LOOK); y++) {
    for (let x = 0; x < info.width; x++) {
      const i = (y * info.width + x) * 4;
      if (data[i + 3] < 160) continue;
      if (data[i] < DARK && data[i + 1] < DARK && data[i + 2] < DARK) {
        sx += x;
        sy += y;
        n++;
      }
    }
  }
  if (n < 400) throw new Error(`${file}: found no eyes (${n} dark pixels) — has the art style changed?`);
  return { x: sx / n / info.width, y: sy / n / info.height + DROP, n };
}

/*
 * Only the grinning render is measured. Feeding always happens on that face —
 * being fed puts the pet in 开心 for the whole act — and the other moods have
 * their eyes half shut or drawn as arcs, which the centroid would read as a
 * lower, narrower face and aim the biscuit at the chin. `mouthOf` strips the
 * suffix so every mood shares its creature's one measurement.
 */
const MOOD_ART = /-(flat|sad|sleepy)(-pink)?\.webp$/;

const files = (await readdir(SRC)).filter((f) => f.endsWith(".webp") && !MOOD_ART.test(f)).sort();
const rows = [];
for (const file of files) {
  const { x, y, n } = await faceOf(file);
  rows.push(`  "${file.replace(/\.webp$/, "")}": [${x.toFixed(4)}, ${y.toFixed(4)}],`);
  console.log(file.padEnd(18), `x=${(x * 100).toFixed(1)}%`, `mouth=${(y * 100).toFixed(1)}%`, `(${n}px of eye)`);
}

await writeFile(
  OUT,
  `/**
 * Where each creature's mouth is, as a fraction of its image's width and
 * height. Generated by \`scripts/build-mouths.mjs\` — do not edit by hand.
 *
 * Feeding carries the food to these coordinates. A single centred target was
 * wrong by up to 9.5% of the image width, because every revealed creature is
 * posed with its head turned away from centre.
 */
const MOUTHS: Record<string, [number, number]> = {
${rows.join("\n")}
};

/** Falls back to the middle of the spread for art with no measurement. */
const FALLBACK: [number, number] = [0.5, 0.48];

export function mouthOf(art: string): [number, number] {
  const id = art
    .replace(/^.*\\//, "")
    .replace(/-(flat|sad|sleepy)(?=(-pink)?\\.webp$)/, "")
    .replace(/\\.webp$/, "");
  return MOUTHS[id] ?? FALLBACK;
}
`,
  "utf8",
);
console.log(`\n${OUT}  ${rows.length} entries`);
