#!/usr/bin/env python3
"""Generate the song table and the font charset.

Two things here would rot if they were written by hand.

The song table has to agree with the order the MP3s are embedded in, because
the embed IO addresses them by index; deriving both from one sorted glob means
they cannot drift.

The charset matters more. Every glyph the firmware can ever draw at runtime is
baked into the bundle at build time, and a character that is not baked comes
out blank on the panel. Static scene text is collected by the compiler, but a
string chosen in C — a caption line, a lyric, a mood name — is invisible to it.
So this walks the real C tables and the real lyrics and writes out exactly the
characters they use. Add a line to pet_lines.c and its glyphs appear; nothing
has to be remembered.

    python3 tools/build_gen.py
"""
from __future__ import annotations

import json
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent.parent
CUES = HERE / "assets/cues.json"
SONG_DIR = HERE / "assets/songs"
CRY_DIR = HERE / "assets/cry"

# Titles as the web app shows them, keyed by track id.
TITLES = {
    "bunny": "小兔子乖乖",
    "tigers": "两只老虎",
    "stars-zh": "小星星",
    "ducks": "数鸭子",
    "radish": "拔萝卜",
    "friends": "找朋友",
    "twinkle": "Twinkle Twinkle",
    "abc": "ABC Song",
    "macdonald": "Old MacDonald",
    "spider": "Itsy Bitsy Spider",
    "lamb": "Mary Had a Little Lamb",
    "boat": "Row Row Row Your Boat",
}

# The order the 儿歌 page lists them in: the Chinese six, then the English six.
ORDER = ["bunny", "tigers", "stars-zh", "ducks", "radish", "friends",
         "twinkle", "abc", "macdonald", "spider", "lamb", "boat"]

ANIMALS = [
    ("dog", "狗"), ("cat", "猫"), ("cow", "牛"), ("duck", "鸭"),
    ("sheep", "羊"), ("pig", "猪"), ("chick", "鸡"), ("frog", "青蛙"),
    ("bird", "鸟"), ("horse", "马"), ("lion", "狮子"), ("elephant", "大象"),
]

CJK = re.compile(r"[\u3000-\u303f\u4e00-\u9fff\uff00-\uffef]")


def c_string(text: str) -> str:
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def song_table() -> tuple[str, list[str]]:
    book = json.loads(CUES.read_text(encoding="utf-8"))
    rows = []
    cue_blocks = []
    embeds = []
    for index, sid in enumerate(ORDER):
        track = SONG_DIR / f"{sid}.mp3"
        if not track.is_file():
            raise SystemExit(f"missing track {track}; run tools/build_assets.py")
        embeds.append(str(track.relative_to(HERE)))
        cues = book.get(sid, {}).get("cues", [])
        # The first cue is the title announcement; the panel already shows the
        # title, so only the sung lines scroll.
        lines = [c for c in cues if c.get("text") != TITLES[sid]]
        name = sid.replace("-", "_")
        cue_blocks.append(
            f"static const song_cue_t CUES_{name}[] = {{\n"
            + "".join(
                f"    {{ {int(round(c['at'] * 1000))}, {c_string(c['text'])} }},\n"
                for c in lines
            )
            + "};\n"
        )
        rows.append(
            f"    {{ {c_string(sid)}, {c_string(TITLES[sid])}, {index}, "
            f"CUES_{name}, {len(lines)} }},"
        )
    body = (
        "".join(cue_blocks)
        + "\nconst song_t SONGS[SONG_COUNT] = {\n"
        + "\n".join(rows)
        + "\n};\n"
    )
    return body, embeds


def animal_table() -> tuple[str, list[str]]:
    rows = []
    embeds = []
    for index, (aid, name) in enumerate(ANIMALS):
        cry = CRY_DIR / f"{aid}.mp3"
        if not cry.is_file():
            raise SystemExit(f"missing cry {cry}; run tools/build_assets.py")
        embeds.append(str(cry.relative_to(HERE)))
        rows.append(f"    {{ {c_string(aid)}, {c_string(name)}, {index} }},")
    return ("\nconst animal_t ANIMALS[ANIMAL_COUNT] = {\n"
            + "\n".join(rows) + "\n};\n"), embeds


def media_table(files: list[str]) -> str:
    """The addresses EMBED_FILES puts in flash, as one array.

    The linker names each blob after its file, so without a table the player
    would need a switch over two dozen symbol pairs. Generating it from the
    same list that feeds EMBED_FILES means the index the UI passes and the
    blob the decoder reads can never point at different tracks.
    """
    names = [Path(f).name for f in files]
    syms = [n.replace(".", "_").replace("-", "_") for n in names]
    externs = "".join(
        f'extern const uint8_t _binary_{s}_start[] asm("_binary_{s}_start");\n'
        f'extern const uint8_t _binary_{s}_end[] asm("_binary_{s}_end");\n'
        for s in syms
    )
    rows = "".join(
        f"    {{ _binary_{s}_start, _binary_{s}_end }},  /* {n} */\n"
        for s, n in zip(syms, names)
    )
    return (
        "/* SPDX-License-Identifier: Apache-2.0 */\n"
        "/* Generated by tools/build_gen.py — do not edit. */\n\n"
        '#include "embedded_media.h"\n\n'
        + externs
        + "\nconst baby_media_t BABY_MEDIA[BABY_MEDIA_COUNT] = {\n"
        + rows
        + "};\n"
    )


def media_header(count: int) -> str:
    return (
        "/* SPDX-License-Identifier: Apache-2.0 */\n"
        "/* Generated by tools/build_gen.py — do not edit. */\n"
        "#pragma once\n\n"
        "#include <stdint.h>\n\n"
        f"#define BABY_MEDIA_COUNT {count}\n\n"
        "typedef struct {\n"
        "    const uint8_t *start;\n"
        "    const uint8_t *end;\n"
        "} baby_media_t;\n\n"
        "extern const baby_media_t BABY_MEDIA[BABY_MEDIA_COUNT];\n"
    )


def charset(sources: list[Path]) -> str:
    """Every character a runtime string can contain."""
    seen: set[str] = set()
    for path in sources:
        for ch in CJK.findall(path.read_text(encoding="utf-8")):
            seen.add(ch)
    return "".join(sorted(seen))


if __name__ == "__main__":
    songs, song_files = song_table()
    animals, cry_files = animal_table()

    gen = HERE / "main/catalog_data.c"
    gen.write_text(
        "/* SPDX-License-Identifier: Apache-2.0 */\n"
        "/* Generated by tools/build_gen.py — do not edit. */\n\n"
        '#include "catalog.h"\n\n'
        + songs + animals,
        encoding="utf-8",
    )
    print(f"  main/catalog_data.c  {len(ORDER)} songs, {len(ANIMALS)} animals")

    (HERE / "main/embedded_media.cmake").write_text(
        "# Generated by tools/build_gen.py — do not edit.\n"
        "set(BABYBAO_EMBED_FILES\n"
        + "".join(f'    "../{f}"\n' for f in song_files + cry_files)
        + ")\n",
        encoding="utf-8",
    )
    print(f"  main/embedded_media.cmake  {len(song_files) + len(cry_files)} files")

    media = song_files + cry_files
    (HERE / "main/embedded_media.h").write_text(media_header(len(media)),
                                                encoding="utf-8")
    (HERE / "main/embedded_media.c").write_text(media_table(media),
                                                encoding="utf-8")
    print(f"  main/embedded_media.[ch]  {len(media)} blobs")

    # Every C source, so a new string is baked the moment it is written and
    # nobody has to remember to list its file here.
    chars = charset(sorted((HERE / "main").glob("*.c")))
    (HERE / "ui/charset.txt").write_text(chars, encoding="utf-8")
    print(f"  ui/charset.txt  {len(chars)} glyphs")
